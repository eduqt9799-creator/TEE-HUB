// Generate 36 rotational frames for the 360-degree interactive viewer
function generate360Frames(frontUrl: string, sideUrl: string, backUrl: string, leftUrl: string): string[] {
  const frames: string[] = [];
  // 36 frames rotating through 360 degrees:
  // 0-8: Front to Right Profile
  // 9-17: Right Profile to Back
  // 18-26: Back to Left Profile
  // 27-35: Left Profile to Front
  for (let i = 0; i < 36; i++) {
    if (i < 5 || i >= 32) {
      frames.push(frontUrl);
    } else if (i >= 5 && i < 14) {
      frames.push(sideUrl);
    } else if (i >= 14 && i < 23) {
      frames.push(backUrl);
    } else {
      frames.push(leftUrl);
    }
  }
  return frames;
}

