function createVariants(productId: string, sizes: ('S' | 'M' | 'L' | 'XL' | 'XXL')[], colors: { name: string; hex: string }[]) {
  return colors.flatMap((color) =>
    sizes.map((size) => ({
      id: `${productId}-${color.name.toLowerCase().replace(/\s+/g, '-')}-${size.toLowerCase()}`,
      size,
      color: color.name,
      colorHex: color.hex,
      stock: Math.floor(Math.random() * 25) + 12, // reliable in-stock inventory
      sku: `TH-${productId.substring(0, 4).toUpperCase()}-${color.name.substring(0, 2).toUpperCase()}-${size}`,
    }))
  );
}

